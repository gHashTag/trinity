import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const h=await import('../src/components/queenHiveDisplay.ts');
assert.equal(h.hiveTaskPaint({state:'review',coverage:'unknown'}).tone,'review','RED: Queen review shares running-bee color');
for(const state of ['blocked','failed','error','refused','rejected']) assert.equal(h.hiveTaskPaint({state,coverage:'t27'}).tone,'blocked');
for(const state of ['dropped','paused','cancelled']) assert.equal(h.hiveTaskPaint({state,coverage:'unknown'}).tone,'paused');
const now=Date.parse('2026-09-07T12:00:00Z');
const e=(kind,state=null,issue=7,at=new Date(now).toISOString(),id='one')=>({kind,state,issue,at,id,title:'Exact issue event'});
assert.equal(h.hiveEventSignal(e('finished','refused')).tone,'blocked');
assert.equal(h.hiveEventSignal(e('result','failed')).tone,'blocked');
assert.equal(h.hiveEventSignal(e('review','wait')).tone,'review');
assert.equal(h.hiveEventSignal(e('review','approved')).tone,'accepted');
assert.equal(h.hiveEventSignal(e('finished')).tone,'result','finished is not accepted or honey');
assert.equal(h.hiveEventSignal(e('result')).tone,'result');
for(const kind of ['dispatch','progress','tool','usage']) assert.equal(h.hiveEventSignal(e(kind)).tone,'active');
const old=e('error',null,7,new Date(now-15001).toISOString(),'old');
const future=e('error',null,7,new Date(now+1).toISOString(),'future');
assert.deepEqual(h.hiveFreshSignals([old,future,e('error',null,null),e('tool'),e('usage')],now),[]);
assert.equal(h.hiveFreshSignals([e('result'),e('error')],now)[0].kind,'error','equal-time error outranks result');
assert.equal(h.hiveFreshSignals([e('error'),e('result',null,7,new Date(now+1).toISOString())],now+1)[0].kind,'result','newer recovery event wins');
assert.equal(h.hiveFreshSignals([e('error'),e('error')],now).length,1);
assert.deepEqual(h.hiveRunningIssueNumbers([{number:7,state:'review'},{number:8,state:'running'}],true),[8]);
assert.deepEqual(h.hiveRunningIssueNumbers([{number:8,state:'running'}],false),[],'stale board cannot animate work');
assert.equal(h.hiveFeedHealth(false,null),'unknown');
assert.equal(h.hiveFeedHealth(true,'HTTP503'),'stale');
assert.equal(h.hiveFeedHealth(false,'HTTP503'),'unknown');
assert.equal(h.hiveFeedHealth(true,null),'live');
const intel=readFileSync(new URL('../src/components/QueenIntel.tsx',import.meta.url),'utf8');
const scene=readFileSync(new URL('../src/components/QueenCombBabylon.tsx',import.meta.url),'utf8');
assert.ok(scene.includes('!displaysRef.current && p !== null'), 'selecting an issue cannot manufacture a colored legacy event flare');
assert.ok(scene.includes('!catalogRef.current && !displaysRef.current && p !== null'), 'selecting a spec cannot manufacture a red fog flare');
assert.ok(intel.includes('hiveEventSignal(event)'), 'intel feed must not show green check for finished/refused');
let cursor={ready:false,seen:new Set()};
const identity=e=>e.kind==='review'?`review:${e.issue}:${e.state}`:e.id;
let delivery=h.hiveSignalDelivery([e('result')],now,'live',cursor,identity);
assert.deepEqual(delivery.events,[],'initial fresh snapshot is baseline, not new activity'); cursor=delivery.cursor;
delivery=h.hiveSignalDelivery([e('error',null,7,new Date(now).toISOString(),'two')],now,'live',cursor,identity);
assert.equal(delivery.events.length,1); cursor=delivery.cursor;
delivery=h.hiveSignalDelivery([],now,'stale',cursor,identity); cursor=delivery.cursor;
delivery=h.hiveSignalDelivery([e('result',null,8,new Date(now).toISOString(),'three')],now,'live',cursor,identity);
assert.deepEqual(delivery.events,[],'reconnect does not replay new snapshot records');
const errorRing=h.hiveSignalRing(null,e('error'),100);
const recovery=h.hiveSignalRing(errorRing,e('result',null,7,new Date(now+1).toISOString()),2500);
assert.equal(recovery.signalColor,'#e7f4ff','new recovery replaces red immediately');
assert.equal(recovery.start,100,'coalesced changes do not restart blink TTL');
assert.equal(h.hiveSignalRing(recovery,e('error'),2700).signalColor,'#e7f4ff','older failure cannot replace newer recovery');
const initial=h.hiveSignalDelivery([],now,'live',{ready:false,seen:new Set()},identity);
const newest=e('result',null,7,new Date(now).toISOString(),'newest');
const first=h.hiveSignalDelivery([newest],now,'live',initial.cursor,identity);
const late=e('error',null,7,new Date(now-1000).toISOString(),'late');
assert.deepEqual(h.hiveSignalDelivery([newest,late],now+4000,'live',first.cursor,identity).events,[],'late older failure must not resurrect after newer result ring expired');
assert.ok(intel.includes('signalLabel'),'event meaning must be accessible text, not only aria-hidden colored icon');
console.log('Hive signals: PASS (lifecycle, failure priority, proof boundaries, event freshness, board-only live work, feed health)');
