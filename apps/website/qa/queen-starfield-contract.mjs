import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { selectHygStars } from '../scripts/import-hyg.mjs';
import { projectCatalogStar, catalogStarRows } from '../src/components/queenStarProjection.ts';
const csv='id,proper,x,y,z,dist,mag,ci\n0,Sol,0,0,0,0,-26,0.65\n1,"Alpha, test",3,4,0,5,2,0.4\n2,Bad,0,0,1,100000,1,0\n3,Dim,3,4,0,5,9,0\n4,Broken,NaN,4,0,5,1,0\n5,Negative,3,4,0,-5,1,0\n';
assert.deepEqual(selectHygStars(csv),[[1,'Alpha, test',3,4,0,5,2,.4]]);
const star=[1,'test',10,0,0,10,2,.4];
assert.deepEqual(catalogStarRows([star,[1,'bad',NaN,0,0,1,1,0],[]]),[star]);
const catalog=JSON.parse(readFileSync(new URL('../src/data/hyg-v41-bright.json',import.meta.url),'utf8'));
assert.equal(catalog.stars.length,4965);
assert.equal(catalogStarRows(catalog.stars).length,4965);
assert.equal(catalog.sourceBlob,'ba2dec4eb0f6768914c7fc1051258100214ddf84');
assert.equal(catalog.license,'CC BY-SA4.0');
const front=projectCatalogStar(star,800,600,{yaw:0,pitch:0,offset:0});
assert.equal(front.x,400); assert.equal(front.y,300); assert.equal(front.depth,10);
assert.equal(projectCatalogStar([2,'back',-10,0,0,10,2,0],800,600,{yaw:0,pitch:0,offset:0}),null);
const near=projectCatalogStar(star,800,600,{yaw:0,pitch:0,offset:.1});
const far=projectCatalogStar([3,'far',100,0,0,100,2,0],800,600,{yaw:0,pitch:0,offset:.1});
assert.ok(Math.abs(near.x-400)>Math.abs(far.x-400), 'real distance affects observer parallax');
const css=readFileSync(new URL('../src/pages/Queen.css',import.meta.url),'utf8');
assert.match(css,/\.queen27-page.is-shell \.queen27-hud-viewport\s*\{[^}]*grid-template-columns: minmax\(0, 1fr\)/, 'outer viewport must stretch the grid track, not only its child');
assert.match(css,/\.queen27-page.is-shell \.queen27-hud-vp-body\s*\{[^}]*grid-template-columns: minmax\(0, 1fr\)/);
assert.match(css,/\.queen-hive-display\s*\{[^}]*var\(--font\)/);
assert.match(css,/\.queen-hive-display\s*\{[^}]*rgba\(3, 14, 18, 0\.4[0-9]\)/);
const scene=readFileSync(new URL('../src/components/QueenCombBabylon.tsx',import.meta.url),'utf8');
assert.match(scene,/scene.clearColor = new Color4\(0, 0, 0, 0\)/);
const renderer=readFileSync(new URL('../src/components/QueenStarfield.tsx',import.meta.url),'utf8');
assert.doesNotMatch(renderer.slice(renderer.indexOf('const draw='),renderer.indexOf('const schedule=')),/document\.hidden/, 'structural redraw must work in background tabs');
assert.match(renderer,/if\(canvas.width!==width\) canvas.width=width/, 'do not reallocate an unchanged high-DPI bitmap');
assert.match(renderer,/new ResizeObserver\(redraw\)/);
console.log('Starfield contract: PASS (catalog filtering, 3D projection/parallax, full-width and branded glass)');
