            \\    output reg [1:0] result [WIDTH-1:0],
            \\    output reg zero,
            \\    output reg overflow
            \\);
            \\
            \\// Balanced ternary encoding: 00=0, 01=-1, 10=+1, 11=invalid
            \\localparam ZEROTRIT = 2'b00;
            \\localparam NEGTRIT  = 2'b01;
            \\localparam POSTRIT  = 2'b10;
            \\
            \\// Opcodes
            \\localparam OP_ADD = 3'b000;
            \\localparam OP_SUB = 3'b001;
            \\localparam OP_MUL = 3'b010;
            \\localparam OP_SACRED_MUL = 3'b011; // φ multiplication
            \\localparam OP_NEG = 3'b100;
