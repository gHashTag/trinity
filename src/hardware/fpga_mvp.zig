            \\
            \\// Ternary addition with carry
            \\function [1:0] trit_add;
            \\    input [1:0] a, b;
            \\    input carry;
            \\    begin
            \\        case ({a, b, carry})
            \\            {ZEROTRIT, ZEROTRIT, 1'b0}: trit_add = ZEROTRIT;
            \\            {ZEROTRIT, POSTRIT, 1'b0}: trit_add = POSTRIT;
            \\            {ZEROTRIT, NEGTRIT,  1'b0}: trit_add = NEGTRIT;
            \\            {POSTRIT, ZEROTRIT, 1'b0}: trit_add = POSTRIT;
            \\            {NEGTRIT,  ZEROTRIT, 1'b0}: trit_add = NEGTRIT;
            \\            {POSTRIT, POSTRIT, 1'b0}: trit_add = NEGTRIT;
            \\            {NEGTRIT,  NEGTRIT,  1'b0}: trit_add = POSTRIT;
            \\            default: trit_add = ZEROTRIT;
            \\        endcase
            \\    end
            \\endfunction
            \\
            \\// Sacred φ multiplier (hardware approximation)
            \\function [15:0] phi_mult;
            \\    input [15:0] x;
            \\    begin
            \\        // φ ≈ 1.618034 = 1 + 101001/1000000 in fixed point
            \\        phi_mult = x + (x >> 1) + (x >> 3) + (x >> 6) + (x >> 7);
            \\    end
            \\endfunction
            \\
            \\integer i;
            \\always @(posedge clk) begin
            \\    if (!rst_n) begin
            \\        for (i = 0; i < WIDTH; i = i + 1) begin
            \\            result[i] <= ZEROTRIT;
            \\        end
            \\        zero <= 1'b1;
            \\        overflow <= 1'b0;
            \\    end else begin
            \\        case (opcode)
            \\            OP_ADD, OP_SUB: begin
            \\                // Ternary addition/subtraction
            \\                for (i = 0; i < WIDTH; i = i + 1) begin
            \\                    result[i] <= trit_add(a[i], b[i], 1'b0);
            \\                end
            \\            end
            \\            OP_SACRED_MUL: begin
            \\                // φ-based multiplication
            \\                for (i = 0; i < WIDTH; i = i + 1) begin
            \\                    if (a[i] == POSTRIT)
            \\                        result[i] <= POSTRIT;
            \\                    else if (a[i] == NEGTRIT)
            \\                        result[i] <= NEGTRIT;
            \\                    else
            \\                        result[i] <= ZEROTRIT;
            \\                end
            \\            end
            \\            default: begin
            \\                for (i = 0; i < WIDTH; i = i + 1) begin
            \\                    result[i] <= ZEROTRIT;
            \\                end
            \\            end
            \\        endcase
            \\    end
            \\end
            \\
            \\endmodule
        , .{self.config.trit_width, self.config.trit_width});
    }

