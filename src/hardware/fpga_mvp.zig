pub const FPGATarget = enum {
    ice40_hx4k,
    ice40_hx8k,
    ice40_up5k,
    fomu,

    pub fn luts(self: FPGATarget) u32 {
        return switch (self) {
            .ice40_hx4k => 3840,
            .ice40_hx8k => 7680,
            .ice40_up5k => 5280,
            .fomu => 6720,
        };
    }

    pub fn bram_kb(self: FPGATarget) u32 {
        return switch (self) {
            .ice40_hx4k => 128,
            .ice40_hx8k => 256,
            .ice40_up5k => 256,
            .fomu => 128,
        };
    }

    pub fn part_name(self: FPGATarget) []const u8 {
        return switch (self) {
            .ice40_hx4k => "iCE40-HX4K-TQFP144",
            .ice40_hx8k => "iCE40-HX8K-TQFP144",
            .ice40_up5k => "iCE40-UP5K-SWG48TR",
            .fomu => "Fomu-EVT",
        };
    }
};

pub const BitstreamConfig = struct {
    target: FPGATarget,
    trit_width: u8 = 8,
    features: u16 = 0b111, // sacred, quantum, koschei

    pub fn estimated_luts(self: BitstreamConfig) u32 {
        var base: u32 = 2000; // Core kernel
        if (self.features & 0b001 != 0) base += 800; // Sacred opcodes
        if (self.features & 0b010 != 0) base += 1200; // Quantum layer
        if (self.features & 0b100 != 0) base += 600; // KOSCHEI
        return @min(base, self.target.luts());
    }

    pub fn utilization_percent(self: BitstreamConfig) f64 {
        return @as(f64, @floatFromInt(self.estimated_luts())) /
               @as(f64, @floatFromInt(self.target.luts())) * 100.0;
    }
};

pub const BitstreamMeta = struct {
    luts_used: u32,
    luts_total: u32,
    bram_used: u32,
    clock_mhz: f64,
    timing_met: bool,
    crc32: u32,
    file_size_kb: u32,

    pub fn format(self: BitstreamMeta, allocator: std.mem.Allocator) ![]u8 {
        return std.fmt.allocPrint(allocator,
            \\TRINITY OS v1.0 Bitstream Metadata
            \\══════════════════════════════════════════
            \\LUTs:     {d}/{d} ({d:.1}%)
            \\BRAM:     {d} KB
            \\Clock:    {d:.1} MHz
            \\Timing:   {s}
            \\CRC32:    0x{x:0>8}
            \\Size:     {d} KB
        , .{
            self.luts_used, self.luts_total,
            @as(f64, @floatFromInt(self.luts_used)) / @as(f64, @floatFromInt(self.luts_total)) * 100.0,
            self.bram_used,
            self.clock_mhz,
            if (self.timing_met) "MET ✓" else "FAILED ✗",
            self.crc32,
            self.file_size_kb,
        });
    }
};

