pub fn demo() !void {
    var gpa = std.heap.GeneralPurposeAllocator(.{}){};
    defer _ = gpa.deinit();
    const allocator = gpa.allocator();

    const MAGENTA = "\x1b[35m";
    const GOLDEN = "\x1b[33m";
    const GREEN = "\x1b[32m";
    const CYAN = "\x1b[36m";
    const RESET = "\x1b[0m";
    const BOLD = "\x1b[1m";

    std.debug.print("\n{s}{s}╔════════════════════════════════════════════════════════════════╗{s}\n", .{ GOLDEN, BOLD, RESET });
    std.debug.print("{s}{s}║     TRINITY FPGA-MVP v1.0 — HARDWARE DEPLOYMENT              ║{s}\n", .{ GOLDEN, BOLD, RESET });
    std.debug.print("{s}{s}║     Lattice iCE40 Bitstream Generation                         ║{s}\n", .{ GOLDEN, BOLD, RESET });
    std.debug.print("{s}{s}╚════════════════════════════════════════════════════════════════╝{s}\n\n", .{ GOLDEN, BOLD, RESET });

    // Configuration
    const config = BitstreamConfig{
        .target = .ice40_hx8k,
        .trit_width = 8,
        .features = 0b111,
    };

    std.debug.print("{s}[CONFIG]{s} Target: {s}{s}{s}\n", .{ CYAN, RESET, BOLD, config.target.part_name(), RESET });
    std.debug.print("  Estimated LUTs: {d}/{d} ({d:.1}%)\n", .{
        config.estimated_luts(),
        config.target.luts(),
        config.utilization_percent(),
    });
    std.debug.print("  BRAM: {d} KB\n\n", .{config.target.bram_kb()});

    // Generate Verilog
    std.debug.print("{s}[STEP 1]{s} Generating Verilog sources...\n", .{ GREEN, RESET });
    var gen = VerilogGenerator.init(allocator, config);
    try gen.generateAll();

    // Show build plan
    var builder = BitstreamBuilder.init(allocator, config);
    try builder.showBuildPlan();

    // Generate synthesis scripts
    std.debug.print("{s}[STEP 2]{s} Generating synthesis scripts...\n", .{ GREEN, RESET });
    const synth_script = try builder.generateSynthScript();
    defer allocator.free(synth_script);

    {
        const file = try std.fs.cwd().createFile("build/synth.ys", .{});
        defer file.close();
        try file.writeAll(synth_script);
    }
    std.debug.print("  → build/synth.ys (Yosys synthesis script)\n", .{});

    std.debug.print("\n{s}{s}╔════════════════════════════════════════════════════════════════╗{s}\n", .{ GOLDEN, BOLD, RESET });
    std.debug.print("{s}{s}║     FPGA-MVP READY FOR SYNTHESIS                              ║{s}\n", .{ GOLDEN, BOLD, RESET });
    std.debug.print("{s}{s}║                                                              ║{s}\n", .{ GOLDEN, BOLD, RESET });
    std.debug.print("{s}{s}║  Next: tri fpga build --all --flash                           ║{s}\n", .{ GREEN, "", RESET });
    std.debug.print("{s}{s}║  Output: build/trinity_os_v1_0.ice bitstream                  ║{s}\n", .{ GOLDEN, BOLD, RESET });
    std.debug.print("{s}{s}╚════════════════════════════════════════════════════════════════╝{s}\n\n", .{ GOLDEN, BOLD, RESET });

    std.debug.print("{s}phi^2 + 1/phi^2 = 3 = TRINITY | KOSCHEI IS THE OPERATING SYSTEM{s}\n\n", .{ CYAN, RESET });
}
