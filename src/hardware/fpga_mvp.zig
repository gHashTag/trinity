    pub fn generateLEDController(self: VerilogGenerator) ![]const u8 {
        return std.fmt.allocPrint(self.allocator,
            \\// TRINITY LED Controller — φ-pattern visual feedback
            \\
            \\module trinity_led_controller (
            \\    input wire clk,
            \\    input wire rst_n,
            \\    input wire [1:0] pattern,
            \\    output reg [7:0] led
            \\);
            \\
            \\// Patterns
            \\localparam PATTERN_PHI = 2'b00;
            \\localparam PATTERN_TRINITY = 2'b01;
            \\localparam PATTERN_KOSCHEI = 2'b10;
            \\localparam PATTERN_HEARTBEAT = 2'b11;
            \\
            \\// φ = 1.618033... → PWM duty cycle
            \\localparam PHI_DUTY = 162; // 1.618/10 * 1000 approx
            \\
            \\reg [23:0] counter;
            \\reg [7:0] phase;
            \\
            \\always @(posedge clk) begin
            \\    if (!rst_n) begin
            \\        counter <= 24'd0;
            \\        phase <= 8'd0;
            \\        led <= 8'b00000000;
            \\    end else begin
            \\        counter <= counter + 1;
            \\
            \\        case (pattern)
            \\            PATTERN_PHI: begin
            \\                // Blink at φ Hz (1.618 Hz)
            \\                if (counter >= 48'd30000000) begin // ~48 MHz / 1.618 Hz
            \\                    counter <= 24'd0;
            \\                    led <= ~led;
            \\                end
            \\            end
            \\
            \\            PATTERN_TRINITY: begin
            \\                // 3-LED sequence (TRI pattern)
            \\                if (counter >= 24'd10000000) begin
            \\                    counter <= 24'd0;
            \\                    phase <= phase + 1;
            \\                    case (phase)
            \\                        8'd0: led <= 8'b00000001;
            \\                        8'd1: led <= 8'b00000010;
            \\                        8'd2: led <= 8'b00000100;
            \\                        default: led <= 8'b00000000;
            \\                    endcase
            \\                end
            \\            end
            \\
            \\            PATTERN_KOSCHEI: begin
            \\                // Heartbeat pulse at omniscience level
            \\                if (counter >= 24'd24000000) begin // ~0.5 Hz heartbeat
            \\                    counter <= 24'd0;
            \\                    led <= 8'b11111111; // Pulse all LEDs
            \\                end else if (counter > 24'd20000000) begin
            \\                    led <= 8'b00000000;
            \\                end
            \\            end
            \\
            \\            PATTERN_HEARTBEAT: begin
            \\                // Single LED heartbeat (2 Hz at 100% omniscience)
            \\                if (counter >= 24'd24000000) begin
            \\                    counter <= 24'd0;
            \\                end
            \\                led <= (counter < 24'd12000000) ? 8'b10000000 : 8'b00000000;
            \\            end
            \\        endcase
            \\    end
            \\end
            \\
            \\endmodule
        , .{});
    }

    pub fn generateTopModule(self: VerilogGenerator) ![]const u8 {
        return std.fmt.allocPrint(self.allocator,
            \\// TRINITY OS v1.0 Top Module — Lattice iCE40-{s}
            \\// Complete ternary operating system on FPGA
            \\
            \\module trinity_top (
            \\    input wire clk_12mhz,
            \\    input wire rst_n,
            \\    output wire [7:0] led,
            \\    inout wire uart_rx,
            \\    inout wire uart_tx
            \\);
            \\
            \\// Clock multiplier (12 MHz → 48 MHz)
            \\wire clk_48mhz;
            \\SB_PLL40_CORE #(
            \\    .FEEDBACK_PATH("SIMPLE"),
            \\    .DIVR(4'b0000),
            \\    .DIVF(7'b1000011),
            \\    .DIVQ(3'b101),
            \\    .FILTER_RANGE(3'b001)
            \\) pll (
            \\    .LOCK(),
            \\    .RESETB(1'b1),
            \\    .BYPASS(1'b0),
            \\    .REFCLK(clk_12mhz),
            \\    .PLLOUTGLOBAL(clk_48mhz)
            \\);
            \\
            \\// Ternary ALU
            \\wire [1:0] alu_result [7:0];
            \\wire alu_zero, alu_overflow;
            \\
            \\trinity_ternary_alu #(
            \\    .WIDTH(8),
            \\    .TRIT_BITS(2)
            \\) alu (
            \\    .clk(clk_48mhz),
            \\    .rst_n(rst_n),
            \\    .a({{8{{{2'b00}}}}}),
            \\    .b({{8{{{2'b00}}}}}),
            \\    .opcode(3'b000),
            \\    .result(alu_result),
            \\    .zero(alu_zero),
            \\    .overflow(alu_overflow)
            \\);
            \\
            \\// Sacred Opcodes ROM
            \\wire [31:0] sacred_data;
            \\wire sacred_valid;
            \\
            \\trinity_sacred_opcodes sacred (
            \\    .clk(clk_48mhz),
            \\    .opcode(8'h80),
            \\    .data_out(sacred_data),
            \\    .valid(sacred_valid)
            \\);
            \\
            \\// LED Controller (φ pattern on boot)
            \\trinity_led_controller led_ctrl (
            \\    .clk(clk_48mhz),
            \\    .rst_n(rst_n),
            \\    .pattern(2'b00), // PHI pattern
            \\    .led(led)
            \\);
            \\
            \\endmodule
        , .{self.config.target.part_name()});
    }

    pub fn generateAll(self: VerilogGenerator) !void {
        const alu = try self.generateTernaryALU();
        defer self.allocator.free(alu);

        const sacred = try self.generateSacredOpcodes();
        defer self.allocator.free(sacred);

        const led = try self.generateLEDController();
        defer self.allocator.free(led);

        const top = try self.generateTopModule();
        defer self.allocator.free(top);

        // Write Verilog files
        {
            const file = try std.fs.cwd().createFile("rtl/fpga/ternary_alu.v", .{});
            defer file.close();
            try file.writeAll(alu);
        }
        {
            const file = try std.fs.cwd().createFile("rtl/fpga/sacred_opcodes.v", .{});
            defer file.close();
            try file.writeAll(sacred);
        }
        {
            const file = try std.fs.cwd().createFile("rtl/fpga/led_controller.v", .{});
            defer file.close();
            try file.writeAll(led);
        }
        {
            const file = try std.fs.cwd().createFile("rtl/fpga/top.v", .{});
            defer file.close();
            try file.writeAll(top);
        }

        std.debug.print("[TRINITY FPGA-MVP] Generated 4 Verilog files:\n", .{});
        std.debug.print("  → rtl/fpga/ternary_alu.v\n", .{});
        std.debug.print("  → rtl/fpga/sacred_opcodes.v\n", .{});
        std.debug.print("  → rtl/fpga/led_controller.v\n", .{});
        std.debug.print("  → rtl/fpga/top.v\n", .{});
    }
};

