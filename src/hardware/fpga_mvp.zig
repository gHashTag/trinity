pub const BitstreamBuilder = struct {
    allocator: std.mem.Allocator,
    config: BitstreamConfig,

    pub fn init(allocator: std.mem.Allocator, config: BitstreamConfig) BitstreamBuilder {
        return .{ .allocator = allocator, .config = config };
    }

    pub fn generateSynthScript(self: BitstreamBuilder) ![]const u8 {
        return std.fmt.allocPrint(self.allocator,
            \\# TRINITY FPGA Synthesis Script — Yosys
            \\# Target: {s}
            \\# LUTs: {d} (estimated: {d:.1}%)
            \\
            \\# Read Verilog sources
            \\read_verilog rtl/fpga/ternary_alu.v
            \\read_verilog rtl/fpga/sacred_opcodes.v
            \\read_verilog rtl/fpga/led_controller.v
            \\read_verilog rtl/fpga/top.v
            \\
            \\# Synthesize for iCE40
            \\synth_ice40 -top trinity_top
            \\
            \\# Write BLIF
            \\write_blif build/trinity.blif
            \\
            \\# Show statistics
            \\stat
        , .{
            self.config.target.part_name(),
            self.config.target.luts(),
            self.config.utilization_percent(),
        });
    }

    pub fn generatePNRScript(self: BitstreamBuilder) ![]const u8 {
        return std.fmt.allocPrint(self.allocator,
            \\# TRINITY FPGA Place & Route Script — NextPNR
            \\# Target: {s}
            \\
            \\# Place and route
            \\--pcf constraints.pcf
            \\--asc build/trinity.asc
            \\build/trinity.blif
        , .{self.config.target.part_name()});
    }

